def set_run_font(run, name_cn="微软雅黑", size=10.5, bold=False, color=None, name_en="Calibri"):
    """统一设置中英文字体。"""
    run.font.name = name_en
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:eastAsia"), name_cn)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)


def add_heading(doc, text, level=1):
    """添加标题并设置中文字体。"""
    h = doc.add_heading("", level=level)
    run = h.add_run(text)
    set_run_font(run, name_cn="微软雅黑", size={1: 16, 2: 13, 3: 11.5}.get(level, 10.5),
                 bold=True, color=(31, 56, 100))
    return h


def add_para(doc, text, size=10.5, bold=False, color=None, indent=None, align=None, space_after=6):
    """添加正文段落。"""
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold, color=color)
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    return p


def add_bullet(doc, text, size=10.5, bold=False, color=None, indent=0.6):
    """添加带"•"符号的列表段落。"""
    p = doc.add_paragraph()
    run = p.add_run(f"•  {text}")
    set_run_font(run, size=size, bold=bold, color=color)
    p.paragraph_format.left_indent = Cm(indent)
    p.paragraph_format.space_after = Pt(3)
    return p


def add_code_block(doc, text, size=9.5):
    """添加公式/代码块（灰底等宽视觉，用缩进+边框模拟）。"""
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_run_font(run, name_cn="Consolas", size=size, color=(51, 51, 51))
    p.paragraph_format.left_indent = Cm(0.8)
    p.paragraph_format.space_after = Pt(6)
    # 添加浅灰底纹
    pPr = p._element.get_or_add_pPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), "F2F4F7")
    pPr.append(shd)
    return p


def add_table(doc, headers, rows, col_widths=None, header_bg="1F3864"):
    """添加带表头底色的表格。"""
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    # 表头
    for j, htext in enumerate(headers):
        cell = table.cell(0, j)
        cell.text = ""
        para = cell.paragraphs[0]
        run = para.add_run(htext)
        set_run_font(run, size=9.5, bold=True, color=(255, 255, 255))
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        # 表头底色
        tcPr = cell._tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear")
        shd.set(qn("w:fill"), header_bg)
        tcPr.append(shd)
    # 数据行
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = table.cell(i + 1, j)
            cell.text = ""
            para = cell.paragraphs[0]
            run = para.add_run(str(val))
            set_run_font(run, size=9.5)
    if col_widths:
        for j, w in enumerate(col_widths):
            for row in table.rows:
                row.cells[j].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return table


def add_caption(doc, text):
    """添加图表小注。"""
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_run_font(run, size=9, color=(120, 120, 120))
    p.paragraph_format.space_after = Pt(8)
    return p


